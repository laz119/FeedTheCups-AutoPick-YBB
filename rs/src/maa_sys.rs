/// 取一个符号并转成函数指针。
unsafe fn resolve<T: Copy>(lib: &libloading::Library, name: &str) -> Result<T, String> {
    let sym: libloading::Symbol<T> = lib
        .get(name.as_bytes())
        .map_err(|e| format!("{name}: {e}"))?;
    Ok(*sym)
}
